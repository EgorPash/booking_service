-- ============================================================
-- 009_booking_service_name_snapshot.sql
-- Снимок названия услуги в записи.
--
-- Цена и длительность уже копируются в саму запись
-- (bookings.price_minor, bookings.duration_min), а название услуги
-- читалось из справочника при показе. Из-за этого переименование
-- услуги в админке меняло вид уже оформленных записей.
--
-- Теперь в записи лежит и её собственный снимок названия.
-- Существующие записи получают название текущего справочника —
-- это лучшее, что можно восстановить задним числом.
-- ============================================================

ALTER TABLE bookings ADD COLUMN service_name TEXT;

UPDATE bookings
SET service_name = (SELECT s.name FROM services s WHERE s.id = bookings.service_id)
WHERE service_name IS NULL;

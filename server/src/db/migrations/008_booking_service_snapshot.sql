-- ============================================================
-- 008_booking_service_snapshot.sql
-- Снимок услуги в записи: рядом с ценой фиксируем и длительность.
--
-- Цена уже хранится снимком (bookings.price_minor). Длительность
-- раньше была видна только через services.duration_min, поэтому
-- правка длительности услуги в справочнике меняла вид старых
-- записей. Теперь в самой записи лежит её собственный снимок:
-- цена и длительность на момент оформления.
--
-- Существующие записи получают длительность из своего интервала
-- (ends_at - starts_at) — это и есть фактическая длительность визита.
-- ============================================================

ALTER TABLE bookings ADD COLUMN duration_min INTEGER NOT NULL DEFAULT 30
  CHECK (duration_min > 0);

UPDATE bookings
SET duration_min = MAX(1, (strftime('%s', ends_at) - strftime('%s', starts_at)) / 60);
